// Helper: get the full localized Living Faith array for the current language,
// falling back to English if the language has not been translated yet.
function getLocalizedLivingFaith() {
  const lang = (typeof AppState !== 'undefined' && AppState.language) || 'en';
  return LIVING_FAITH_I18N[lang] || LIVING_FAITH_I18N.en;
}

// Shared week-of-year index so English and Yoruba stay on the same reflection.
function getLivingFaithWeekIndex() {
  const list = getLocalizedLivingFaith();
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  return Math.floor(dayOfYear / 7) % list.length;
}

// Helper: get today's Living Faith using the localized array (replaces the
// English-only getTodayLivingFaith() from livingfaith.js for display purposes)
function getTodayLocalizedLivingFaith() {
  const list = getLocalizedLivingFaith();
  return list[getLivingFaithWeekIndex()];
}
